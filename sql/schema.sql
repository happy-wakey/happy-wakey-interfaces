CREATE TABLE IF NOT EXISTS happy_wakey_alarms (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id TEXT NOT NULL,
  label TEXT NOT NULL,
  local_time TIME NOT NULL,
  time_zone TEXT NOT NULL,
  weekdays JSONB NOT NULL,
  enabled BOOL NOT NULL DEFAULT true,
  sound TEXT NOT NULL,
  volume DECIMAL(4,3) NOT NULL,
  gradual_seconds INT4 NOT NULL DEFAULT 0,
  tags JSONB NOT NULL DEFAULT '[]'::JSONB,
  generation INT8 NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp(),
  CONSTRAINT happy_wakey_alarm_volume CHECK (volume >= 0 AND volume <= 1),
  CONSTRAINT happy_wakey_alarm_generation CHECK (generation >= 0),
  CONSTRAINT happy_wakey_alarm_gradual CHECK (gradual_seconds >= 0 AND gradual_seconds <= 1800)
);

CREATE INDEX IF NOT EXISTS happy_wakey_alarms_owner_enabled
  ON happy_wakey_alarms (owner_id, enabled, updated_at DESC);

CREATE TABLE IF NOT EXISTS happy_wakey_alarm_occurrences (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  alarm_id UUID NOT NULL REFERENCES happy_wakey_alarms(id) ON DELETE CASCADE,
  owner_id TEXT NOT NULL,
  scheduled_for TIMESTAMPTZ NOT NULL,
  state STRING NOT NULL,
  generation INT8 NOT NULL DEFAULT 0,
  active_transition_id UUID NULL,
  snooze_until TIMESTAMPTZ NULL,
  acknowledged_at TIMESTAMPTZ NULL,
  completed_at TIMESTAMPTZ NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp(),
  CONSTRAINT happy_wakey_occurrence_state CHECK (state IN ('scheduled','firing','acknowledged','snoozed','completed','missed','canceled')),
  CONSTRAINT happy_wakey_occurrence_generation CHECK (generation >= 0),
  UNIQUE (alarm_id, scheduled_for)
);

CREATE INDEX IF NOT EXISTS happy_wakey_occurrences_due
  ON happy_wakey_alarm_occurrences (state, scheduled_for);
CREATE INDEX IF NOT EXISTS happy_wakey_occurrences_owner
  ON happy_wakey_alarm_occurrences (owner_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS happy_wakey_transition_receipts (
  transition_id UUID PRIMARY KEY,
  owner_id TEXT NOT NULL,
  occurrence_id UUID NULL REFERENCES happy_wakey_alarm_occurrences(id) ON DELETE CASCADE,
  request_hash TEXT NOT NULL,
  disposition TEXT NOT NULL,
  response JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp(),
  -- `pending` is an internal, transactional claim. It is never returned in the
  -- public TransitionDisposition enum and cannot survive a rolled-back write.
  CONSTRAINT happy_wakey_transition_disposition CHECK (disposition IN ('pending','applied','stale','rejected'))
);

CREATE TABLE IF NOT EXISTS happy_wakey_sync_changes (
  sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  change_id UUID NOT NULL UNIQUE,
  scope TEXT NOT NULL,
  collection TEXT NOT NULL,
  entity_id UUID NOT NULL,
  operation TEXT NOT NULL,
  generation INT8 NOT NULL,
  actor_id TEXT NOT NULL,
  document JSONB NULL,
  occurred_at TIMESTAMPTZ NOT NULL,
  CONSTRAINT happy_wakey_sync_operation CHECK (operation IN ('upsert','delete')),
  CONSTRAINT happy_wakey_sync_generation CHECK (generation >= 0),
  CONSTRAINT happy_wakey_sync_document CHECK ((operation = 'delete' AND document IS NULL) OR (operation = 'upsert' AND document IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS happy_wakey_sync_scope_sequence
  ON happy_wakey_sync_changes (scope, sequence);

CREATE TABLE IF NOT EXISTS happy_wakey_async_operations (
  operation_id UUID PRIMARY KEY,
  owner_id TEXT NOT NULL,
  operation TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  response JSONB NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp(),
  completed_at TIMESTAMPTZ NULL,
  CONSTRAINT happy_wakey_async_operation_kind CHECK (operation IN ('list_alarms')),
  CONSTRAINT happy_wakey_async_operation_status CHECK (status IN ('pending','completed')),
  CONSTRAINT happy_wakey_async_operation_response CHECK (
    (status = 'pending' AND response IS NULL AND completed_at IS NULL)
    OR (status = 'completed' AND response IS NOT NULL AND completed_at IS NOT NULL)
  )
);

CREATE INDEX IF NOT EXISTS happy_wakey_async_operations_pending
  ON happy_wakey_async_operations (status, expires_at, created_at);

-- ---------------------------------------------------------------------------
-- Morning dashboard desired state.
--
-- Two rules govern everything below. First, no provider credential appears in
-- any column: a connection carries `credential_ref`, an opaque handle resolved
-- inside the secret boundary, and the polyglot gate asserts that no column
-- named for a token, key, secret or password exists here. Second, physiological
-- records are owner-partitioned and deleted with their source connection, so a
-- disconnect is a real erasure rather than a hidden retention.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS happy_wakey_provider_connections (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id TEXT NOT NULL,
  provider TEXT NOT NULL,
  domain TEXT NOT NULL,
  display_name TEXT NOT NULL,
  auth_kind TEXT NOT NULL,
  content_class TEXT NOT NULL,
  feed_class TEXT NOT NULL,
  requested_capabilities JSONB NOT NULL DEFAULT '[]'::JSONB,
  granted_capabilities JSONB NOT NULL DEFAULT '[]'::JSONB,
  status TEXT NOT NULL DEFAULT 'not_connected',
  credential_ref TEXT NULL,
  last_sync_at TIMESTAMPTZ NULL,
  next_sync_after TIMESTAMPTZ NULL,
  last_failure JSONB NULL,
  rate_budget JSONB NULL,
  generation INT8 NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT current_timestamp(),
  CONSTRAINT happy_wakey_provider_domain CHECK (domain IN ('calendar','mail','messaging','health','markets','environment','tasks','news','commute')),
  CONSTRAINT happy_wakey_provider_content_class CHECK (content_class IN ('none','counts_only','metadata_only','full_content')),
  CONSTRAINT happy_wakey_provider_feed_class CHECK (feed_class IN ('real_time','delayed','end_of_day','on_sync','unknown')),
  CONSTRAINT happy_wakey_provider_status CHECK (status IN ('not_connected','pending_consent','connected','degraded','rate_limited','expired','revoked','unsupported_platform','policy_unavailable')),
  CONSTRAINT happy_wakey_provider_generation CHECK (generation >= 0),
  UNIQUE (owner_id, provider, display_name)
);

CREATE INDEX IF NOT EXISTS happy_wakey_provider_connections_due
  ON happy_wakey_provider_connections (status, next_sync_after);
CREATE INDEX IF NOT EXISTS happy_wakey_provider_connections_owner
  ON happy_wakey_provider_connections (owner_id, domain, updated_at DESC);

CREATE TABLE IF NOT EXISTS happy_wakey_sleep_summaries (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id TEXT NOT NULL,
  source_connection_id UUID NOT NULL REFERENCES happy_wakey_provider_connections(id) ON DELETE CASCADE,
  night_of DATE NOT NULL,
