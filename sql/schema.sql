  owner_id TEXT NOT NULL,
  day DATE NOT NULL,
  time_zone TEXT NOT NULL,
  working_hours_start_local TIME NOT NULL,
  working_hours_end_local TIME NOT NULL,
  capacity JSONB NOT NULL DEFAULT '{}'::JSONB,
  energy_curve JSONB NOT NULL DEFAULT '[]'::JSONB,
